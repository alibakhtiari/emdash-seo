import type { SeoPluginOptions } from '../types.js';

/** AI crawler user-agents governed by the block-AI toggle. */
const AI_BOTS = ['GPTBot', 'ClaudeBot', 'PerplexityBot', 'Google-Extended', 'CCBot'];

export interface RobotsKnobs {
  /** Extra raw `Disallow:`/`Allow:` lines from seo_settings or options. */
  customRules?: string[];
  /** When true, AI crawlers get `Disallow: /` (except llms endpoints stay open). */
  blockAiBots?: boolean;
  /** Passed through as `Crawl-delay: N` under `User-agent: *`. */
  crawlDelay?: number;
}

function knobsFromOptions(options: SeoPluginOptions): RobotsKnobs {
  const o = options as SeoPluginOptions & {
    robotsRules?: string[];
    robotsCustomRules?: string[];
    blockAiBots?: boolean;
    crawlDelay?: number;
  };
  return {
    customRules: o.robotsRules ?? o.robotsCustomRules,
    blockAiBots: o.blockAiBots,
    crawlDelay: o.crawlDelay,
  };
}

async function knobsFromSettings(ctx: any): Promise<Partial<RobotsKnobs>> {
  const out: Partial<RobotsKnobs> = {};
  try {
    const get = async (key: string): Promise<string | undefined> => {
      if (ctx?.settings?.get) {
        const v = await ctx.settings.get(key);
        if (v != null) return String(v);
      }
      if (ctx?.kv?.get) {
        const v = await ctx.kv.get(`settings:${key}`);
        if (v != null) return String(v);
      }
      return undefined;
    };
    const raw = await get('robots_custom_rules');
    if (raw) out.customRules = raw.split('\n').map((l) => l.trim()).filter(Boolean);
    const blockAi = await get('robots_block_ai');
    if (blockAi != null) out.blockAiBots = blockAi === '1' || blockAi === 'true';
    const delay = await get('robots_crawl_delay');
    if (delay != null && delay !== '' && !Number.isNaN(Number(delay))) {
      out.crawlDelay = Number(delay);
    }
  } catch {
    // Fall back to option-level knobs
  }
  return out;
}

export function buildRobotsTxt(options: SeoPluginOptions, knobs: RobotsKnobs = {}): string {
  const siteUrl = options.siteUrl.replace(/\/+$/, '');
  const merged: RobotsKnobs = { ...knobsFromOptions(options), ...knobs };
  const lines: string[] = ['# Robots.txt (Generated by EmDash SEO Suite)', 'User-agent: *'];

  const customs = (merged.customRules || []).map((l) => l.trim()).filter(Boolean);
  if (customs.length > 0) {
    lines.push(...customs);
  } else {
    lines.push('Disallow: /_emdash/', 'Disallow: /api/', 'Allow: /', 'Disallow: /*?s=', 'Disallow: /search/');
  }
  if (merged.crawlDelay != null) lines.push(`Crawl-delay: ${merged.crawlDelay}`);

  lines.push('', '# Sitemaps', `Sitemap: ${siteUrl}/sitemap.xml`, `Sitemap: ${siteUrl}/sitemap-index.xml`);

  lines.push('', '# AI Agent Directives');
  for (const bot of AI_BOTS) {
    lines.push(`User-agent: ${bot}`);
    lines.push(merged.blockAiBots ? 'Disallow: /' : 'Allow: /');
    if (!merged.blockAiBots) {
      lines.push('Allow: /llms.txt', 'Allow: /llms-full.txt');
    }
  }
  return `${lines.join('\n')}\n`;
}

export function renderRobots(_ctx: any, options: SeoPluginOptions): Response {
  return new Response(buildRobotsTxt(options), {
    status: 200,
    headers: {
      'Content-Type': 'text/plain; charset=utf-8',
      'Cache-Control': 'public, max-age=86400',
    },
  });
}

/** Settings-driven variant: merges seo_settings custom rules over option knobs. */
export async function renderRobotsAsync(ctx: any, options: SeoPluginOptions): Promise<Response> {
  const fromSettings = await knobsFromSettings(ctx);
  return new Response(buildRobotsTxt(options, fromSettings), {
    status: 200,
    headers: {
      'Content-Type': 'text/plain; charset=utf-8',
      'Cache-Control': 'public, max-age=86400',
    },
  });
}
